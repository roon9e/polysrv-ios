#!/usr/bin/env python3
"""
apply_polysrv.py - Overlay the PolySRV multiserver code onto a clean upstream
Telegram-iOS tree, in place, and apply the anchored edits it needs.

Usage:
    python3 build-system/polysrv/apply_polysrv.py [repo_root] [--check|--revert]

The tool works on the same principle as build-system/apply_branding.py, with two
parts:

  1. OVERLAY - every file under build-system/polysrv/overlay/ is copied verbatim
     into the tree, preserving its relative path. This holds the new PolySRV
     sources (server model, store, UI) that upstream has no equivalent for.
     Those paths are additive only: nothing upstream is overwritten, so an
     upstream merge never conflicts with them.

  2. EDITS - build-system/polysrv/edits.py describes the small anchored
     search/replace changes the runtime hook needs in upstream files (the DC
     seed list, the account datacenter, MtProtoKit's key and DC locking, the
     Rust engine factory). Every anchor must exist; a missing one is a hard
     failure so a build never silently ships an unpatched tree.

  servers.json is the single source of truth for the default server list; the
  bundled Swift fallback (PolySrvDefaultServers.swift) is generated from it here
  so the two can never drift.

Flags:
  --check    report what would change and exit non-zero if anything is pending;
             change nothing.
  --revert   restore the tree: git-checkout the edited files and delete the
             overlay-copied and generated files.

Exit code: 0 when every transform was applied (or, with --check, when nothing is
pending), 1 otherwise.
"""
import argparse
import base64
import os
import shutil
import subprocess
import sys

import edits as edits_module

WIDTH = 64

# Files copied by the overlay, tracked so --revert can remove them and --check
# can report them.
OVERLAY_DIR_NAME = "overlay"

# Relative path of the generated bundled-server fallback inside the tree.
GENERATED_DEFAULT_SERVERS = "submodules/TelegramCore/Sources/PolySrv/PolySrvDefaultServers.swift"


def read(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def read_normalized(path):
    """Return (text_with_LF, uses_crlf).

    The anchors in edits.py are written with LF. A Windows checkout (or any
    autocrlf=true tree) hands back CRLF, so matching is done on a normalised
    copy and the file's own line endings are restored on write.
    """
    with open(path, "r", encoding="utf-8", newline="") as f:
        raw = f.read()
    crlf = "\r\n" in raw
    return raw.replace("\r\n", "\n"), crlf


def write(path, text):
    parent = os.path.dirname(path)
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def write_preserving(path, text, crlf):
    if crlf:
        text = text.replace("\n", "\r\n")
    write(path, text)


class Applied:
    def __init__(self):
        self.failures = []
        self.applied = []

    def ok(self, what):
        print("[apply_polysrv] ok: " + what)
        self.applied.append(what)

    def fail(self, what):
        print("[apply_polysrv] MISSING ANCHOR: " + what)
        self.failures.append(what)


def overlay_files(overlay_root):
    """Relative paths of every file under the overlay directory."""
    result = []
    for dirpath, _dirnames, filenames in os.walk(overlay_root):
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            result.append(os.path.relpath(full, overlay_root))
    return sorted(result)


def default_servers_swift(servers_json_path):
    """Generate the Swift fallback from servers.json.

    The JSON is embedded base64-encoded: a Swift multiline string would still
    process the \\n escapes the JSON uses inside the RSA key, and hand-escaping
    the tree of quotes is exactly the kind of brittleness this repo avoids.
    """
    with open(servers_json_path, "rb") as f:
        data = f.read()
    encoded = base64.b64encode(data).decode("ascii")
    lines = [
        "// Generated by build-system/polysrv/apply_polysrv.py from",
        "// build-system/polysrv/servers.json. Do not edit: edit the JSON and",
        "// re-run the script.",
        "",
        "let polySrvDefaultServersJSONBase64 = \"" + encoded + "\"",
        "",
    ]
    return "\n".join(lines)


def apply_edits(root, state):
    for edit in edits_module.EDITS:
        rel = edit["file"]
        old = edit["old"]
        new = edit["new"]
        label = edit.get("label", rel)
        count = edit.get("count", 1)
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            state.fail(label + " (" + rel + " is missing)")
            continue
        text, crlf = read_normalized(path)
        # Idempotent when re-run over an already-patched tree, and over a tree
        # that is genuinely upstream-clean when new != old.
        if count == "all":
            if new in text:
                state.ok(label + " (already applied)")
                continue
            if old not in text:
                state.fail(label)
                continue
            occurrences = text.count(old)
            write_preserving(path, text.replace(old, new), crlf)
            state.ok("%s (%d occurrence(s))" % (label, occurrences))
        else:
            if new in text:
                state.ok(label + " (already applied)")
                continue
            if old not in text:
                state.fail(label)
                continue
            write_preserving(path, text.replace(old, new, 1), crlf)
            state.ok(label)


def apply_overlay(root, overlay_root, state):
    for rel in overlay_files(overlay_root):
        src = os.path.join(overlay_root, rel)
        dst = os.path.join(root, rel)
        should_copy = True
        if os.path.isfile(dst):
            if read(src) == read(dst):
                should_copy = False
        if should_copy:
            parent = os.path.dirname(dst)
            if parent and not os.path.isdir(parent):
                os.makedirs(parent)
            shutil.copyfile(src, dst)
            state.ok("overlay: " + rel)
        else:
            state.ok("overlay: " + rel + " (up to date)")


def generate_default_servers(root, servers_json_path, state):
    text = default_servers_swift(servers_json_path)
    dst = os.path.join(root, GENERATED_DEFAULT_SERVERS)
    if os.path.isfile(dst) and read(dst) == text:
        state.ok("generated: " + GENERATED_DEFAULT_SERVERS + " (up to date)")
        return
    write(dst, text)
    state.ok("generated: " + GENERATED_DEFAULT_SERVERS)


def run_check(root, overlay_root, servers_json_path):
    """Report pending changes without touching the tree."""
    pending = []
    for rel in overlay_files(overlay_root):
        src = os.path.join(overlay_root, rel)
        dst = os.path.join(root, rel)
        if not os.path.isfile(dst) or read(src) != read(dst):
            pending.append("overlay: " + rel)
    gen = default_servers_swift(servers_json_path)
    dst = os.path.join(root, GENERATED_DEFAULT_SERVERS)
    if not os.path.isfile(dst) or read(dst) != gen:
        pending.append("generated: " + GENERATED_DEFAULT_SERVERS)
    for edit in edits_module.EDITS:
        rel = edit["file"]
        label = edit.get("label", rel)
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            pending.append(label + " (" + rel + " is missing)")
            continue
        text, _crlf = read_normalized(path)
        if edit.get("count", 1) == "all":
            if edit["new"] in text:
                pass
            elif edit["old"] in text:
                pending.append(label)
            else:
                pending.append(label + " (anchor missing)")
        elif edit["new"] not in text:
            if edit["old"] in text:
                pending.append(label)
            else:
                pending.append(label + " (anchor missing)")
    if pending:
        print("[apply_polysrv] %d change(s) pending:" % len(pending))
        for what in pending:
            print("  - " + what)
        return 1
    print("[apply_polysrv] check: tree is fully patched.")
    return 0


def run_revert(root, overlay_root):
    # Edited upstream files are tracked: restore them.
    tracked = []
    for edit in edits_module.EDITS:
        rel = edit["file"]
        if rel not in tracked:
            tracked.append(rel)
    if tracked:
        subprocess.check_call(["git", "-C", root, "checkout", "--"] + tracked)
        print("[apply_polysrv] restored %d edited file(s)" % len(tracked))
    # Overlay copies and the generated file are untracked: delete them.
    removed = 0
    for rel in overlay_files(overlay_root):
        dst = os.path.join(root, rel)
        if os.path.isfile(dst):
            os.remove(dst)
            removed += 1
    generated = os.path.join(root, GENERATED_DEFAULT_SERVERS)
    if os.path.isfile(generated):
        os.remove(generated)
        removed += 1
    # Drop now-empty PolySrv directories so a re-apply starts clean.
    for rel in set([os.path.dirname(r) for r in overlay_files(overlay_root)] + ["submodules/TelegramCore/Sources/PolySrv"]):
        directory = os.path.join(root, rel)
        if os.path.isdir(directory) and not os.listdir(directory):
            try:
                os.rmdir(directory)
            except OSError:
                pass
    print("[apply_polysrv] removed %d overlay file(s)" % removed)
    return 0


def main(argv):
    parser = argparse.ArgumentParser(add_help=True)
    parser.add_argument("root", nargs="?", default=os.getcwd(), help="repo root (default: cwd)")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--revert", action="store_true")
    args = parser.parse_args(argv[1:])

    here = os.path.dirname(os.path.abspath(__file__))
    overlay_root = os.path.join(here, OVERLAY_DIR_NAME)
    servers_json_path = os.path.join(here, "servers.json")
    root = args.root

    if not os.path.isdir(overlay_root):
        print("[apply_polysrv] missing overlay directory: " + overlay_root)
        return 1
    if not os.path.isfile(servers_json_path):
        print("[apply_polysrv] missing servers.json: " + servers_json_path)
        return 1

    if args.revert:
        return run_revert(root, overlay_root)
    if args.check:
        return run_check(root, overlay_root, servers_json_path)

    state = Applied()
    apply_overlay(root, overlay_root, state)
    apply_edits(root, state)
    generate_default_servers(root, servers_json_path, state)

    if state.failures:
        print("[apply_polysrv] %d transform(s) could not be applied:" % len(state.failures))
        for what in state.failures:
            print("  - " + what)
        return 1
    print("[apply_polysrv] done.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
